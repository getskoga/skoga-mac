import Foundation

/// Seed data mirrors `data.jsx` in the design bundle verbatim — same names,
/// statuses, repos, tokens, costs. Swap for a real client once skogad is wired up.
@MainActor
final class MockDaemonClient: DaemonClient {

    private let agentsCache: [Agent] = MockDaemonClient.seedAgents
    private let conversationCache: [String: [ConversationMessage]] = MockDaemonClient.seedConversations
    private let timelineCache: [TimelineEntry] = MockDaemonClient.seedTimeline
    private let activityCache: [Double] = MockDaemonClient.seedActivity

    /// In-memory `gh` status the mock client returns. Designers can flip
    /// fields in `seedGitHubStatus` (or via `githubSetDefaultReviewer` at
    /// runtime) to exercise each Settings → GitHub variant without
    /// running a real daemon. Mutable because `set_default_reviewer`
    /// rewrites the persisted reviewer in place.
    private var githubStatusState: RPCGitHubStatus = MockDaemonClient.seedGitHubStatus

    func listAgents() async throws -> [Agent] { agentsCache }

    func conversation(for agentId: String) async throws -> [ConversationMessage] {
        conversationCache[agentId] ?? []
    }

    func activitySeries() async throws -> [Double] { activityCache }

    func timeline(for agentId: String) async throws -> [TimelineEntry] {
        // The design ships one timeline (Astrid's) and reuses it for all agents.
        timelineCache
    }

    func daemonVersion() async throws -> String { "mock" }

    func createSession(task: String, agent: String, model: String?, base: String, repoRoot: URL, initialPrompt: String?) async throws -> Agent {
        // No-op in mock mode; the design has no notion of starting a real session.
        throw NSError(domain: "MockDaemonClient", code: 0,
                      userInfo: [NSLocalizedDescriptionKey: "Dispatch requires a live skogad. Unset SKOGA_USE_MOCK."])
    }

    func killSession(id: String) async throws {
        // No-op.
    }

    func sendInput(sessionId: String, text: String) async throws {
        // No-op. Mock mode has no real agent to forward to; succeeding
        // silently lets designers exercise the composer end-to-end.
    }

    func pendingQuestion(for agentId: String) async throws -> RPCPendingQuestion? {
        // No-op for the mock — designers exercise the question UI via
        // the seeded `.question(...)` conversation rows, not the live
        // pending_question RPC.
        nil
    }

    func answerQuestion(sessionId: String, selectedIndices: [Int]) async throws {
        // No-op. The mock has no live agent to drive.
    }

    nonisolated func events() -> AsyncStream<RPCEvent> {
        AsyncStream { $0.finish() }
    }

    func openPTYStream(sessionId: String, cols: UInt16?, rows: UInt16?) async throws -> AttachedPTYStream {
        // Mock has no agent process — return an empty stream so the
        // Native pane shows up blank instead of hanging on a phantom
        // attach. Designers exercising the TUI surface should run against
        // a real skogad.
        throw NSError(domain: "MockDaemonClient", code: 0,
                      userInfo: [NSLocalizedDescriptionKey: "Native pane requires a live skogad. Unset SKOGA_USE_MOCK."])
    }

    func ptyWrite(sessionId: String, bytes: Data) async throws {}
    func ptyResize(sessionId: String, cols: UInt16, rows: UInt16) async throws {}

    func previewPR(for sessionId: String) async throws -> PRPreview {
        // Pull what we know about the mock agent so the modal pre-fill at
        // least looks plausible during design review. The CLI's real preview
        // computes this from session metadata too, so the shapes line up.
        let agent = agentsCache.first(where: { $0.id == sessionId })
        let task = agent?.task ?? "Mock session"
        return PRPreview(
            title: task.hasSuffix(".") ? String(task.dropLast()) : task,
            body: "\(task)\n\nGenerated by Skoga session \(sessionId)"
        )
    }

    func landPR(for sessionId: String, title: String, body: String) async throws {
        // Pretend the land succeeded. No way to actually push from mock —
        // the design surface is the only thing consuming this path.
        try await Task.sleep(nanoseconds: 400_000_000)
    }

    func githubStatus() async throws -> RPCGitHubStatus {
        githubStatusState
    }

    @discardableResult
    func githubSetDefaultReviewer(_ reviewer: String) async throws -> RPCGitHubStatus {
        let trimmed = reviewer.trimmingCharacters(in: .whitespacesAndNewlines)
        let current = githubStatusState
        githubStatusState = RPCGitHubStatus(
            installed: current.installed,
            authenticated: current.authenticated,
            login: current.login,
            default_account: current.default_account,
            scopes: current.scopes,
            default_reviewer: trimmed.isEmpty ? nil : trimmed
        )
        return githubStatusState
    }
}

